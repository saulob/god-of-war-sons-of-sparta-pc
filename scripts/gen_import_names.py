HEADER = ('/* NID -> symbol name for the eboot and bundled-module imports (diagnostics and runtime lookup).\n'
          ' * Generated by scripts/gen_import_names.py; names from shadPS4 aerolib. */\n')


def load_aerolib(path):
    names = {}
    for line in Path(path).read_text(errors='replace').splitlines():
        m = re.search(r'STUB\(\s*"([^"]+)"\s*,\s*([^)\s]+)\s*\)', line)
        if m:
            names[m.group(1)] = m.group(2)
    names.update(EXTRA_NAMES)
    return names


def canonical(name):
    nid, _, lib = name.partition('#')
    if lib == 'libScePosix':
        lib = 'libkernel'  # runtime.c canonical_name()
    return f'{nid}#{lib}'


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--image', type=Path, required=True, help='image.json written by prepare_image.py')
    parser.add_argument('--aerolib', type=Path, default=os.environ.get('SOS_AEROLIB'))
    args = parser.parse_args()
    if not args.aerolib or not Path(args.aerolib).is_file():
        parser.error('aerolib.inl not found: pass --aerolib or set SOS_AEROLIB')
    names = load_aerolib(args.aerolib)
    report = json.loads(args.image.read_text())
    found = {}
    missing = []
    for name in report['import_list']:
        nid = name.split('#')[0]
        if nid in names:
            found[canonical(name)] = names[nid]
        else:
            missing.append(name)
    for nid, library, name in DYNAMIC_NAMES:
        found[f'{nid}#{library}'] = name
    INC.parent.mkdir(parents=True, exist_ok=True)
    INC.write_text(HEADER + ''.join(f'{{"{k}","{v}"}},\n' for k, v in sorted(found.items())), newline='\n')
    print(f'{len(found)} names written to {INC}')
    if missing:
        print(f'{len(missing)} imports not named by aerolib:', file=sys.stderr)
        for name in sorted(missing):
            print(f'  {name}', file=sys.stderr)


if __name__ == '__main__':
    main()
